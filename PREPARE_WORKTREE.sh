#!/usr/bin/env bash
# prepare-worktree.sh — product-delivery worktree setup for Deep Create
# Usage: ./PREPARE_WORKTREE.sh
# Exit codes: 0 = success, 1 = environment failure (node/pnpm missing), 2 = build failure
# Note: this delegates to the canonical org-root prepare-worktree.sh + build-env.sh.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ORG_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

log() { printf '[prepare-worktree] %s\n' "$*"; }
err() { printf '[prepare-worktree] ERROR: %s\n' "$*" >&2; }

if [ -f "$ORG_ROOT/prepare-worktree.sh" ]; then
    log "delegating to canonical org prepare-worktree.sh"
    exec bash "$ORG_ROOT/prepare-worktree.sh"
fi

# Fallback: inline if org script missing
command -v node >/dev/null 2>&1 || { err "node not found in PATH (need >=22.12.0 <23)"; exit 1; }
command -v pnpm >/dev/null 2>&1 || { err "pnpm not found in PATH (need 12.3.4)"; exit 1; }

NODE_VER=$(node --version | sed 's/v//')
PNPM_VER=$(pnpm --version)
log "node $NODE_VER, pnpm $PNPM_VER"

log "pnpm install --frozen-lockfile"
pnpm install --frozen-lockfile || { err "pnpm install failed"; exit 2; }

log "pnpm run ui:build"
pnpm run ui:build || { err "ui:build failed"; exit 2; }

if [ -f "crates/dc-desktop/permissions/autogenerated/work_unit_ids.toml" ]; then
    log "work_unit_ids.toml present"
else
    log "work_unit_ids.toml not found (may be created by tauri build)"
fi

log "cargo check -p dc-desktop (via MSVC env)"
powershell -NoProfile -Command ". ./tools/Enter-BuildEnvironment.ps1; cargo check -p dc-desktop" \
    || { err "cargo check -p dc-desktop failed"; exit 2; }

log "prepare-worktree complete"
exit 0
